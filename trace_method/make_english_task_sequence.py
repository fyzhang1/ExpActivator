"""Plot consecutive recorded task screens with separately evaluated predictions.

Original screenshot files and result files are read only. Arrows encode recording
order, not transitions generated by the evaluated policy. No image synthesis.
"""
from pathlib import Path
import hashlib
import json
import re

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.patches import Circle, FancyArrowPatch, FancyBboxPatch
from PIL import Image

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "trace_method/results/english_case_candidates"
DATA = Path("/storage/zhangfuyao/datasets/fingertip20k")
EPISODE = "43_20250425_171909"
BLUE, RED, INK, MUTED = "#2166B5", "#AD433D", "#172B44", "#59687B"


def read(path):
    return json.loads(path.read_text())


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def action(a):
    if a["action"] == "click":
        return "click({}, {})".format(*a["coordinate"])
    return a["action"]


def main():
    OUT.mkdir(exist_ok=True)
    tex = (REPO / "manuscript/paper/iclr2027/iclr2027_conference.tex").read_text()
    name = re.search(r"\\newcommand\{\\methodname\}\{([^}]+)\}", tex).group(1)
    plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 11,
                         "pdf.fonttype": 42, "ps.fonttype": 42})
    targets = {int(r["id"].rsplit("_", 1)[1]): r for r in read(
        REPO / "data/personal_execution/personal_execution.json")
        if r["id"].rsplit("_", 1)[0] == EPISODE}
    files = {
        name: "grounded/qwen3_vl_8b_grounded_policy_gpu0.json",
        "Step index": "state_conditioning/qwen3_vl_8b/top1_ordinal_policy_gpu0.json",
        "Current screen (one history)": "state_conditioning/qwen3_vl_8b/top1_state_policy_gpu0.json",
        "Previous screen": "leap_ablations/refresh/delay1_policy_gpu0.json",
        "Update every four steps": "leap_ablations/refresh/refresh4_policy_gpu0.json",
    }
    result_paths = {k: REPO / "trace_method/results" / v for k, v in files.items()}
    results = {k: {r["episode_id"]: r for r in read(p)["outputs"]}
               for k, p in result_paths.items()}
    assert sorted(targets) == list(range(10))
    paths = {i: DATA / r["img_path"].removeprefix("./data/Fingertip/")
             for i, r in targets.items() if i > 0}
    timestamps = [int(paths[i].stem) for i in range(1, 10)]
    assert timestamps == sorted(timestamps)
    names = {1: "App launcher", 2: "App loading", 3: "Stops loading",
             4: "Nearby stops", 5: "Destination field", 6: "Building search",
             7: "Recommended routes", 8: "Route details loading", 9: "Route details"}

    def screen(fig, i, box, font=11, point=False):
        ax = fig.add_axes(box)
        with Image.open(paths[i]) as im:
            width, height = im.size
            ax.imshow(im, interpolation="antialiased")
        ax.set_xticks([])
        ax.set_yticks([])
        for spine in ax.spines.values():
            spine.set_color(BLUE if i == 7 else "#D0D8E2")
            spine.set_linewidth(2.5 if i == 7 else .7)
        ax.set_title(f"Step {i}  |  {names[i]}", fontsize=font,
                     color=BLUE if i == 7 else INK, pad=13,
                     fontweight="bold" if i == 7 else "normal")
        if point:
            a = results[name][targets[i]["id"]]["output"]
            x, y = a["coordinate"]
            center = (x / 999 * width, y / 999 * height)
            for color, lw, radius in [("white", 5, .071), (BLUE, 2.8, .071)]:
                ax.add_patch(Circle(center, width * radius, fill=False,
                                    edgecolor=color, linewidth=lw))
        pred = results[name][targets[i]["id"]]
        ax.text(.5, -.033, f"{name}: {action(pred['output'])}",
                transform=ax.transAxes, ha="center", va="top", fontsize=font - 1,
                color=INK)
        ax.text(.5, -.075, f"Benchmark SR = {pred['sr']}",
                transform=ax.transAxes, ha="center", va="top", fontsize=font - 1,
                color=BLUE if pred["sr"] else RED)
        return ax

    fig = plt.figure(figsize=(17, 10), facecolor="white")
    fig.text(.035, .956, "A relevant history still needs the right step", fontsize=23,
             color=INK, fontweight="bold")
    fig.text(.035, .92,
             "Task (translated): Check the next bus departures from PGPR to the MRT station.",
             fontsize=13, color=INK)
    fig.text(.035, .887,
             "Five consecutive recorded observations  |  NUS NextBus  |  Qwen3-VL-8B",
             fontsize=11, color=MUTED)
    for j, i in enumerate(range(3, 8)):
        x = .035 + j * .19
        screen(fig, i, [x, .27, .168, .565], point=(i == 7))
        if j < 4:
            fig.add_artist(FancyArrowPatch((x + .173, .57), (x + .185, .57),
                           transform=fig.transFigure, arrowstyle="-|>",
                           mutation_scale=16, linewidth=1.3, color="#8999AD"))
    panels = [
        (.035, "At step 7: select within the same historical trajectory",
         "Step index: terminate (SR 0)    |    Current screen: click A1 (SR 1)",
         "The step-index reference has already reached the end of its historical task."),
        (.515, "At step 7: update references from eight candidate histories",
         f"{name}: click A1 (SR 1)    |    Previous screen / every four steps: SR 0",
         "Stale references lead to clicks in blank space or the start-location field."),
    ]
    for x, title, line, explanation in panels:
        fig.add_artist(FancyBboxPatch((x, .058), .45, .13,
                       boxstyle="round,pad=0.008,rounding_size=0.008",
                       transform=fig.transFigure, facecolor="#EBF5FF",
                       edgecolor="#C7DCF2", linewidth=.7))
        fig.text(x + .012, .159, title, fontsize=11.5, fontweight="bold", color=INK)
        fig.text(x + .012, .121, line, fontsize=10.5, color=BLUE)
        fig.text(x + .012, .086, explanation, fontsize=10, color=MUTED)
    fig.text(.035, .02,
             "Arrows show recording order. Predictions are evaluated separately at each screen; "
             "SR is the benchmark step score. Blue circle: actual policy click.",
             fontsize=10, color=MUTED)
    for ext in ("pdf", "png"):
        fig.savefig(OUT / f"leaf_task_sequence.{ext}", dpi=220)
    plt.close(fig)

    fig = plt.figure(figsize=(16, 14.5), facecolor="white")
    fig.text(.035, .967, "One recorded task, from app launch to route details",
             fontsize=22, fontweight="bold", color=INK)
    fig.text(.035, .938, f"Episode {EPISODE}  |  All 9 task screenshots in order  |  {name} / Qwen3-VL-8B",
             fontsize=12, color=MUTED)
    for j, i in enumerate(range(1, 10)):
        row, col = divmod(j, 5)
        x, y = .035 + col * .19, .53 if row == 0 else .085
        screen(fig, i, [x, y, .168, .365], font=10, point=(i == 7))
        if col < 4 and i < 9:
            fig.add_artist(FancyArrowPatch((x + .172, y + .19), (x + .186, y + .19),
                           transform=fig.transFigure, arrowstyle="-|>", mutation_scale=15,
                           linewidth=1.1, color="#8999AD"))
    ax = fig.add_axes([.81, .15, .16, .29]); ax.axis("off")
    ax.text(0, .95, "Reading this sequence", fontsize=13, fontweight="bold", color=INK)
    ax.text(0, .82,
            "Read left to right,\nthen continue on row 2.\n\n"
            "Screens come from the\nrecorded user task.\n\n"
            "The predictions do not\ngenerate the next screenshot.\n\n"
            f"All {name} failures in these\n9 steps remain visible.\n\n"
            "Step 0 is a shared desktop\nplaceholder, not a task\nscreenshot; it is omitted.",
            fontsize=11, color=MUTED, va="top", linespacing=1.45)
    fig.text(.035, .025,
             "Original screens, including native language content, are preserved. "
             "SR is the recorded benchmark score, not an independent annotation of each visible target.",
             fontsize=10, color=MUTED)
    for ext in ("pdf", "png"):
        fig.savefig(OUT / f"leaf_task_sequence_full.{ext}", dpi=180)
    plt.close(fig)

    caption = (
        "Consecutive recorded observations from a NUS NextBus task. "
        "At step 7, current-screen selection clicks the visible A1 route, whereas "
        "step-index selection within the same historical trajectory terminates. "
        "With eight candidate histories, LEAF also clicks A1, while references "
        "selected from the previous screen or refreshed every four steps fail "
        "on this observation. The arrows indicate recording order; policy "
        "predictions are evaluated separately on each recorded screen and "
        "do not constitute a successful closed-loop rollout. All displayed "
        "step scores are retained, including failures. The task instruction "
        "is translated for presentation; screenshot contents are unchanged."
    )
    (OUT / "leaf_task_sequence_caption.txt").write_text(caption + "\n")
    latex_caption = caption.replace("LEAF", r"\methodname{}")
    (OUT / "leaf_task_sequence_figure.tex").write_text(
        "\\begin{figure}[t]\n\\centering\n"
        "\\includegraphics[width=\\linewidth]{../../../trace_method/results/english_case_candidates/leaf_task_sequence.pdf}\n"
        "\\caption{" + latex_caption + "}\n"
        "\\label{fig:leaf-task-sequence}\n\\end{figure}\n")
    manifest = {
        "episode_id": EPISODE, "method_name": name, "model": "Qwen3-VL-8B",
        "selection": "Same episode as previously audited A1 example, outcome-selected for qualitative illustration.",
        "compact_steps": list(range(3, 8)), "full_steps": list(range(1, 10)),
        "omitted_step_0": targets[0],
        "caption": caption,
        "rendering": "Original image arrays embedded in matplotlib; no screenshot translation, synthesis, or retouching. Only the exact current policy click at step 7 is circled.",
        "limitations": [
            "Some historical reference coordinates disagree with their content labels; they are not drawn as correct targets.",
            "Benchmark SR can disagree with visual target interpretation; all recorded scores are retained.",
            "This task contains failed LEAF steps and cannot be presented as a complete successful execution.",
            "The full sequence contains Chinese launcher text and map labels; the compact app sequence has English UI.",
            "HIM-Agent, Recent and LLM-UM also succeed at step 7.",
        ],
        "result_files": {str(p): digest(p) for p in result_paths.values()},
        "steps": [{"index": i, "target": targets[i], "screenshot": str(paths[i]),
                   "sha256": digest(paths[i]),
                   "outputs": {v: rows[targets[i]["id"]] for v, rows in results.items()}}
                  for i in range(1, 10)],
    }
    (OUT / "task_sequence_evidence.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n")
    print(OUT / "leaf_task_sequence.pdf")
    print(OUT / "leaf_task_sequence_full.pdf")


if __name__ == "__main__":
    main()
